<?php

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$libraryPath = $argv[1]
    ?? dirname(__DIR__) . '/www/GoogleAuthenticator.php';

require $libraryPath;

$passed = 0;
$failed = 0;

function check($condition, $description)
{
    global $passed, $failed;

    if ($condition) {
        echo "PASS: {$description}\n";
        $passed++;
    } else {
        echo "FAIL: {$description}\n";
        $failed++;
    }
}

$ga = new PHPGangsta_GoogleAuthenticator();

// Public test secret from RFC 4226 Appendix D, encoded as Base32.
// This is test data, not an actual account secret.
$secret = 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ';

$expectedCodes = [
    '755224',
    '287082',
    '359152',
    '969429',
    '338314',
    '254676',
    '287922',
    '162583',
    '399871',
    '520489'
];

// Expected results are published reference values,
// not values generated by the implementation under test.
foreach ($expectedCodes as $counter => $expected) {
    check(
        $ga->getCode($secret, $counter) === $expected,
        "Reference code matches at counter {$counter}"
    );
}

// Fixed current time step: 5. No dependency on the real clock.
check(
    $ga->verifyCode($secret, '254676', 0, 5),
    'Correct current code is accepted'
);

check(
    !$ga->verifyCode($secret, '000000', 0, 5),
    'Incorrect six-digit code is rejected'
);

check(
    $ga->verifyCode($secret, '338314', 1, 5),
    'Previous time-step code is accepted with tolerance 1'
);

check(
    $ga->verifyCode($secret, '287922', 1, 5),
    'Next time-step code is accepted with tolerance 1'
);

check(
    !$ga->verifyCode($secret, '969429', 1, 5),
    'Code two time steps old is rejected'
);

check(
    !$ga->verifyCode($secret, '162583', 1, 5),
    'Code two time steps ahead is rejected'
);

check(
    !$ga->verifyCode($secret, '338314', 0, 5),
    'Previous code is rejected when tolerance is zero'
);

foreach (['', '12345', '1234567', 'abcdef'] as $invalid) {
    check(
        !$ga->verifyCode($secret, $invalid, 1, 5),
        'Invalid code input is rejected: ' . json_encode($invalid)
    );
}

foreach ([16, 32, 128] as $length) {
    $generated = $ga->createSecret($length);

    check(
        strlen($generated) === $length &&
        preg_match('/^[A-Z2-7]+$/', $generated) === 1,
        "Generated {$length}-character secret has valid Base32 format"
    );
}

foreach ([15, 129] as $length) {
    $rejected = false;

    try {
        $ga->createSecret($length);
    } catch (Exception $e) {
        $rejected = $e->getMessage() === 'Bad secret length';
    }

    check(
        $rejected,
        "Unsupported secret length {$length} is rejected"
    );
}

echo "\nResults: {$passed} passed, {$failed} failed.\n";
exit($failed === 0 ? 0 : 1);